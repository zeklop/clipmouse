const store = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* приватный режим — переживём */ } }
};

/* ---------- язык ---------- */

let lang = store.get("cm-lang");
if (lang !== "ru" && lang !== "en") {
  lang = (navigator.language || "").toLowerCase().startsWith("ru") ? "ru" : "en";
}

function applyLang() {
  const dict = I18N[lang];
  document.documentElement.lang = lang;
  document.title = dict._title;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value != null) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = dict[el.dataset.i18nHtml];
    if (value != null) el.innerHTML = value;
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.langBtn === lang));
  });
}

document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
  btn.addEventListener("click", () => {
    lang = btn.dataset.langBtn;
    store.set("cm-lang", lang);
    applyLang();
  });
});

/* ---------- тема ---------- */

/* Скриншоты с парой «тёмный/светлый»: src — тёмный вариант, data-light-src — светлый. */
function applyThemeShots(theme) {
  document.querySelectorAll("img[data-light-src]").forEach((img) => {
    if (!img.dataset.darkSrc) img.dataset.darkSrc = img.getAttribute("src");
    img.setAttribute("src", theme === "light" ? img.dataset.lightSrc : img.dataset.darkSrc);
  });
}

function applyTheme(theme) {
  document.documentElement.dataset.theme = theme;
  applyThemeShots(theme);
  document.querySelectorAll("[data-theme-toggle]").forEach((btn) => {
    btn.setAttribute("aria-label", theme === "dark" ? "Switch to light theme" : "Switch to dark theme");
  });
}

const storedTheme = store.get("cm-theme");
const initialTheme =
  storedTheme === "light" || storedTheme === "dark"
    ? storedTheme
    : (window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light");

applyTheme(initialTheme);
applyLang();

document.querySelectorAll("[data-theme-toggle]").forEach((btn) => {
  btn.addEventListener("click", () => {
    const next = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
    store.set("cm-theme", next);
    applyTheme(next);
  });
});

/* ---------- галерея настроек: вкладки как в приложении ---------- */

const settingsImg = document.querySelector("img[data-settings-img]");
if (settingsImg) {
  const tabs = document.querySelectorAll("[data-settings-tab]");
  tabs.forEach((btn) => {
    btn.addEventListener("click", () => {
      tabs.forEach((b) => b.setAttribute("aria-selected", String(b === btn)));
      settingsImg.setAttribute("src", btn.dataset.settingsTab);
      settingsImg.setAttribute("alt", "ClipMouse — settings window, " + btn.textContent + " tab");
    });
  });
}

/* ---------- копирование команд в буфер ---------- */

document.querySelectorAll(".copy-btn").forEach((btn) => {
  btn.addEventListener("click", async () => {
    const text = btn.dataset.copy;
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      const dict = I18N[lang] || I18N.ru;
      const textEl = btn.querySelector(".copy-text") || btn;
      const originalText = dict.inst_copy || "Копировать";
      textEl.textContent = dict.inst_copied || "✓ Скопировано";
      btn.classList.add("copied");
      setTimeout(() => {
        textEl.textContent = dict.inst_copy || originalText;
        btn.classList.remove("copied");
      }, 2000);
    } catch {
      /* приватный режим или блокировка буфера */
    }
  });
});
